@OptIn(ExperimentalLayoutApi::class)
@Preview(showBackground = true, heightDp = 5000)
@Composable
private fun IconPoolPreview() {
    HocusPocusFocusTheme {
        Column(Modifier.verticalScroll(rememberScrollState()).padding(16.dp)) {
            val quickIcons = mapOf("quickRoutineIcons" to quickRoutineIcons, "quickTaskIcons" to quickTaskIcons)
            val sections = quickIcons + IconPool.entries.groupBy { it.category }
            sections.forEach { (category, icons) ->
                Text(
                    category,
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    modifier = Modifier.padding(top = 16.dp),
                )
                FlowRow(
                    horizontalArrangement = Arrangement.spacedBy(12.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp),
                ) {
                    icons.forEach {
                        Icon(
                            painterResource(it.drawable),
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.primary)
                    }
                }
            }
        }
    }
}

